#!/usr/bin/env bash
# Writes .env with random secrets when it does not exist. Never overwrites an existing .env.
set -euo pipefail
cd "$(dirname "$0")/.."

if [[ -f .env ]]; then
  echo ".env exists; leaving it unchanged"
  exit 0
fi

python - <<'PY'
import secrets
names = [line.split("=", 1)[0] for line in open(".env.example", encoding="utf-8")
         if "=" in line and not line.startswith("#")]
with open(".env", "w", encoding="utf-8", newline="\n") as f:
    f.write("# Generated by scripts/init-env.sh. Local lab secrets; never commit.\n")
    for name in names:
        # SQL Server password policy: upper, lower, digit, and symbol.
        f.write(f"{name}=Fp1-{secrets.token_hex(16)}\n")
PY
echo "wrote .env with random values"
