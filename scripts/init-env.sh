#!/usr/bin/env bash
# Writes .env with random secrets when it does not exist. An existing .env is never changed, except
# that names added to .env.example since it was written are appended with new random values.
set -euo pipefail
cd "$(dirname "$0")/.."

python - <<'PY'
import os
import secrets

names = [line.split("=", 1)[0] for line in open(".env.example", encoding="utf-8")
         if "=" in line and not line.startswith("#")]
exists = os.path.exists(".env")
present = set()
if exists:
    present = {line.split("=", 1)[0] for line in open(".env", encoding="utf-8")
               if "=" in line and not line.startswith("#")}
missing = [name for name in names if name not in present]
with open(".env", "a" if exists else "w", encoding="utf-8", newline="\n") as f:
    if not exists:
        f.write("# Generated by scripts/init-env.sh. Local lab secrets; never commit.\n")
    for name in missing:
        # SQL Server password policy: upper, lower, digit, and symbol.
        f.write(f"{name}=Fp1-{secrets.token_hex(16)}\n")
if not exists:
    print("wrote .env with random values")
elif missing:
    print("appended to .env: " + ", ".join(missing))
else:
    print(".env complete; leaving it unchanged")
PY
